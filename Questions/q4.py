# Q4. Type Conversion: `"250"` ko integer aur float mein convert karo. 
# Converted values ke data types verify karo.
num = "250"
integer_num = int(num)
float_num = float(num)
print("Integer value : ",integer_num)
print("Integer type : ",type(integer_num))

print("Float value : ", float_num)
print("Float type : ", type(float_num))