# Q6. Variable Swapping: Do variables ki values swap karo 
# using a temporary variable, phir temporary variable ke bina try karo.
a = 4
b = 5
print("Before swapping : ")
print("a : ",a)
print("b : ",b)
tem_var = a
a = b
b = tem_var
print("After swapping : ")
print("a : ",a)
print("b : ",b)

